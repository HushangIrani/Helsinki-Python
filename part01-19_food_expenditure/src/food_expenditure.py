Cafeteria_Times = int(input("How many times a week do you eat at the student cafeteria? "))
Cafeteria_Price = float(input("The price of a typical student lunch? "))
Groceries_Weekly_Price = float(input("How much money do you spend on groceries in a week? "))
print("Average food expenditure:")
print(f"Daily: {((Cafeteria_Times * Cafeteria_Price) + Groceries_Weekly_Price) / 7} euros")
print(f"Weekly: {(Cafeteria_Times * Cafeteria_Price) + Groceries_Weekly_Price} euros")